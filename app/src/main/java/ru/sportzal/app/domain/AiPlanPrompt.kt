package ru.sportzal.app.domain

/** Offline hand-off contract: the user chooses an AI chat and attaches the exported report. */
object AiPlanPrompt {
    fun build(schema: String): String = """
        Подготовь следующий план тренировок для приложения «Спортзал».
        Моя цель, опыт, частота занятий и ограничения: [дополню здесь].
        Я приложу sportzal.ai_snapshot: каталог оборудования, текущий план и фактические результаты.
        Если данных для плана недостаточно, сначала задай уточняющие вопросы.
        Учитывай фактические веса, повторы, запас повторов, замены, пропуски и мои комментарии.
        Не подменяй фактические результаты плановыми. Не назначай вес на заменённом оборудовании по старому тренажёру.
        Верни готовый UTF-8 файл program.json без Markdown-обёртки по JSON Schema ниже.
        Правила совместимости:
        - schema = sportzal.program, schema_version = 1.
        - Для продолжения сохраняй program_id, увеличивай program_version относительно active_program и всех сохранённых версий этого program_id.
        - Для каждой новой тренировки создай новый workout_instance_id: уже начатые или завершённые ID повторно не используй.
        - Сохраняй equipment_id существующих тренажёров. equipment_upserts может быть пустым, если каталог не меняется.
        - Сохраняй exercise_id для того же движения; exercise_instance_id должен быть уникальным внутри тренировки.
        - Все обязательные поля, единицы веса, load_basis, side и допустимые значения должны соответствовать схеме.
        - generated_at — ISO 8601 с часовым поясом, planned_date — YYYY-MM-DD, set_no — подряд от 1.
        - Если report отсутствует, сначала попроси его; если история пуста, уточни исходные данные и не выдумывай результаты.
        Короткое объяснение изменений помести в coach_notes. Настройку и технику опиши понятным текстом в соответствующих полях.

        JSON Schema:
        $schema
    """.trimIndent()
}
